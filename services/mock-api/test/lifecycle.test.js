import { test } from 'node:test'
import assert from 'node:assert/strict'
import { start, resetState } from '../server.js'

test('customer order updates kitchen, rider, stock, invoice, and finance', async () => {
  resetState()
  const server = await start(8791)
  const base = 'http://127.0.0.1:8791'
  const call = (path, opts = {}) => fetch(base + path, {
    method: opts.method || 'GET',
    headers: { 'content-type': 'application/json', ...(opts.token ? { authorization: `Bearer ${opts.token}` } : {}) },
    body: opts.body ? JSON.stringify(opts.body) : undefined,
  })
  const login = async (identifier, role) => {
    const response = await call('/v1/auth/login', { method: 'POST', body: { identifier, password: 'password12', role } })
    assert.equal(response.status, 200)
    return (await response.json()).token
  }
  try {
    const customer = await login('03001234567', 'customer')
    const owner = await login('owner@bakecharm.test', 'vendor_owner')
    const staff = await login('staff@bakecharm.test', 'vendor_staff')
    const rider = await login('03007654321', 'rider')
    assert.equal((await call('/v1/slots/2030/hold', { method: 'POST', token: customer, body: {} })).status, 200)
    const created = await call('/v1/orders', { method: 'POST', token: customer, body: { slotId: '2030', delivery: 'express', payment: 'Cash on delivery', lines: [{ id: 'cake', qty: 1, price: 1 }] } })
    assert.equal(created.status, 201)
    const order = await created.json()
    assert.equal(order.status, 'new')
    assert.equal(order.food, 1850)
    assert.notEqual(order.code, '482913')
    assert.equal((await call('/v1/slots/1830/hold', { method: 'POST', token: customer, body: {} })).status, 200)
    const fragile = await call('/v1/orders', { method: 'POST', token: customer, body: { slotId: '1830', delivery: 'pooled', lines: [{ id: 'cake', qty: 1 }] } })
    assert.equal(fragile.status, 409)
    assert.equal((await call(`/v1/orders/${order.id}/accept`, { method: 'POST', token: staff, body: { screen: 'E7-US3-UI1' } })).status, 200)
    const marked = await call(`/v1/orders/${order.id}/ready`, { method: 'POST', token: staff, body: {} })
    assert.equal(marked.status, 200)
    const readyOrder = await marked.json()
    assert.equal(readyOrder.status, 'ready')
    assert.equal(readyOrder.rider.name, 'Hamza Ali')
    const riderReady = await (await call('/v1/state', { token: rider })).json()
    assert.equal(riderReady.orders.find((item) => item.id === order.id).status, 'ready')
    assert.equal(riderReady.alerts.some((alert) => alert.orderId === order.id && alert.type === 'pickup' && alert.status === 'open'), true)
    const customerReady = await (await call('/v1/state', { token: customer })).json()
    assert.equal(customerReady.orders.find((item) => item.id === order.id).rider.name, 'Hamza Ali')
    const picked = await call(`/v1/orders/${order.id}/pickup`, { method: 'POST', token: rider, body: {} })
    assert.equal(picked.status, 200)
    assert.equal((await picked.json()).status, 'picked_up')
    const repeated = await call(`/v1/orders/${order.id}/pickup`, { method: 'POST', token: rider, body: {} })
    assert.equal(repeated.status, 200)
    assert.equal((await repeated.json()).status, 'picked_up')
    const wrong = await call(`/v1/orders/${order.id}/deliver`, { method: 'POST', token: rider, body: { code: '000000' } })
    assert.equal(wrong.status, 400)
    const done = await call(`/v1/orders/${order.id}/deliver`, { method: 'POST', token: rider, body: { code: order.code } })
    assert.equal(done.status, 200)
    const state = await (await call('/v1/state', { token: owner })).json()
    assert.equal(state.orders[0].status, 'delivered')
    assert.equal(state.invoices.length, 1)
    assert.ok(state.finance.revenue > 0)
    assert.ok(state.stock.find((item) => item.id === 'flour').quantity < 8)
    const staffState = await (await call('/v1/state', { token: staff })).json()
    assert.equal(staffState.recipes, null)
    assert.equal(staffState.finance, null)
    const stranger = await call('/v1/orders', { method: 'POST', body: { slotId: '1830', lines: [{ id: 'cake', qty: 1 }] } })
    assert.equal(stranger.status, 401)
    assert.equal((await call('/v1/slots/1900/hold', { method: 'POST', token: customer, body: {} })).status, 200)
    const second = await (await call('/v1/orders', { method: 'POST', token: customer, body: { slotId: '1900', delivery: 'express', payment: 'Cash on delivery', lines: [{ id: 'cake', qty: 1 }] } })).json()
    assert.equal((await call(`/v1/orders/${second.id}/accept`, { method: 'POST', token: owner, body: {} })).status, 200)
    assert.equal((await call(`/v1/orders/${second.id}/ready`, { method: 'POST', token: owner, body: {} })).status, 200)
    const handed = await call(`/v1/orders/${second.id}/handoff`, { method: 'POST', token: owner, body: {} })
    assert.equal(handed.status, 200)
    const handedOrder = await handed.json()
    assert.equal(handedOrder.status, 'ready_for_pickup')
    assert.notEqual(handedOrder.status, 'picked_up')
    assert.equal(handedOrder.rider.name, 'Hamza Ali')
    const afterHand = await call(`/v1/orders/${second.id}/pickup`, { method: 'POST', token: rider, body: {} })
    assert.equal(afterHand.status, 200)
    const collected = await afterHand.json()
    assert.equal(collected.status, 'picked_up')
    assert.equal(collected.rider.name, 'Hamza Ali')
    const seen = await (await call('/v1/state', { token: customer })).json()
    assert.equal(seen.orders.find((item) => item.id === second.id).rider.name, 'Hamza Ali')
  } finally {
    server.close()
  }
})
